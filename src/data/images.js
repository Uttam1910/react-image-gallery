export const getEnrichedImages = (apiPhotos = []) => {
  if (!apiPhotos || apiPhotos.length === 0) {
    return initialImages;
  }
  
  return apiPhotos.map((photo, index) => {
    const baseMatch = initialImages[index % initialImages.length];
    return {
      ...baseMatch,
      id: photo.id || baseMatch.id,
      url: photo.url || baseMatch.url,
      // Ensure realistic metadata replaces any raw sample text
      title: (photo.title && !photo.title.includes('Reflect') && !photo.title.includes('Drug')) 
        ? photo.title 
        : baseMatch.title,
      description: (photo.description && !photo.description.includes('Reflect') && !photo.description.includes('Drug')) 
        ? photo.description 
        : baseMatch.description,
    };
  });
};
